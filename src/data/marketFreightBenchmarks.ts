// Helper to generate 12-week historical trend data
const generate12WeekHistory = (
  baseMedian: number, 
  spreadPercent: number = 0.15, 
  trendSlope: number = 0.02
): HistoricalRatePoint[] => {
  const weeks = [
    { label: 'W-11', date: '11 tuần trước', scfiMult: 0.91 },
    { label: 'W-10', date: '10 tuần trước', scfiMult: 0.92 },
    { label: 'W-9', date: '9 tuần trước', scfiMult: 0.94 },
    { label: 'W-8', date: '8 tuần trước', scfiMult: 0.95 },
    { label: 'W-7', date: '7 tuần trước', scfiMult: 0.97 },
    { label: 'W-6', date: '6 tuần trước', scfiMult: 0.99 },
    { label: 'W-5', date: '5 tuần trước', scfiMult: 1.01 },
    { label: 'W-4', date: '4 tuần trước', scfiMult: 1.03 },
    { label: 'W-3', date: '3 tuần trước', scfiMult: 1.02 },
    { label: 'W-2', date: '2 tuần trước', scfiMult: 1.04 },
    { label: 'W-1', date: 'Tuần trước', scfiMult: 1.05 },
    { label: 'Hiện tại', date: 'Tuần này', scfiMult: 1.06 },
  ];

  return weeks.map((w, index) => {
    const factor = 1 - (11 - index) * trendSlope;
    const median = Math.round(baseMedian * factor);
    const low = Math.round(median * (1 - spreadPercent));
    const high = Math.round(median * (1 + spreadPercent * 1.3));
    const scfi = Math.round(2050 * w.scfiMult);
    return {
      weekLabel: w.label,
      date: w.date,
      scfiIndex: scfi,
      marketMedianSpot: median,
      marketLowSpot: low,
      marketHighSpot: high,
      ourCompanyRate: Math.round(median * 0.98),
    };
  });
};

